import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const workerPath = resolve(root, "dist/server/index.js");
const manifestPath = resolve(root, "dist/.openai/hosting.json");
const migrationPath = resolve(root, "drizzle/0000_steep_terrax.sql");
const [source, manifest, migration] = await Promise.all([readFile(workerPath, "utf8"), readFile(manifestPath, "utf8"), readFile(migrationPath, "utf8")]);
assert.equal(JSON.parse(manifest).d1, "DB", "Leaderboard D1 binding must be enabled");
assert.match(migration, /CREATE TABLE `leaderboard_scores`/, "Leaderboard migration must create its table");
const worker = await import(`data:text/javascript;base64,${Buffer.from(source).toString("base64")}`);
assert.equal(typeof worker.default?.fetch, "function", "Worker must export default.fetch");
const statement = { bind() { return this; }, async all() { return { results: [] }; }, async run() { return { success: true }; } };
const env = { DB: { prepare() { return statement; } } };
const listResponse = await worker.default.fetch(new Request("https://page-breaker.test/api/leaderboard"), env);
assert.equal(listResponse.status, 200, "Leaderboard list route must respond");
const saveResponse = await worker.default.fetch(new Request("https://page-breaker.test/api/leaderboard", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ playerName: "PLAYER", website: "example.com", destroyed: 10, total: 20, durationMs: 12000, score: 1500 }) }), env);
assert.equal(saveResponse.status, 201, "Leaderboard submission route must respond");
console.log("Artifact is valid");
